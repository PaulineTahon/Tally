import { chromium } from 'playwright-core'
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-blink-features=AutomationControlled'] })
const ctx = await b.newContext({ viewport: { width: 1400, height: 900 }, userAgent: 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36' })
const g = await ctx.newPage()
await g.goto('https://www.officedemy.com/how-to-share-google-form/', { waitUntil: 'domcontentloaded', timeout: 25000 }); await g.waitForTimeout(2000)
const gi = g.locator('img[src*="How-to-share-Google-Form-2.png"]').first(); await gi.scrollIntoViewIfNeeded(); await g.waitForTimeout(800); await gi.screenshot({ path: '/tmp/research/gf2.png' })
const c = await ctx.newPage()
await c.goto('https://www.canva.com/help/share-on-socials-and-messaging/', { waitUntil: 'domcontentloaded', timeout: 25000 }); await c.waitForTimeout(4000)
console.log(c.url(), await c.title())
const imgs = await c.evaluate(() => [...document.images].map((i) => [i.naturalWidth, i.alt.slice(0,60), i.currentSrc.slice(0,120)]))
console.log(JSON.stringify(imgs.slice(0, 15)))
await c.screenshot({ path: '/tmp/research/canva-page.png' })
await b.close()
